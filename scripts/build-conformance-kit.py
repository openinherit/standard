"""Build @openinherit/conformance's INVALID fixtures and manifest.

Every INVALID fixture is one VALID fixture with ONE operation applied, as
declared in packages/conformance/mutations.json together with the rule the
operation breaks. That is what makes "each INVALID case targets one rule"
something a machine can check rather than something a README claims.

Writes, under packages/conformance/:
  <mode>/invalid/<id>.json        the mutant
  expected/<id>.expected.json     its verdict, the rule, and how it was made
  manifest.json                   every case and bundled schema with its sha256,
                                  at the package's version

VALID fixtures and their expected files are authored by hand and only read.

USAGE: python3 scripts/build-conformance-kit.py [--root <dir>] [--check]
  --check   write nothing; exit 1 if the kit on disk differs from a rebuild
EXIT CODES: 0 clean - 1 the kit is stale (--check) or a VALID fixture has no
expected file - 2 cannot answer.
"""
import argparse
import hashlib
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from lib.conformance_kit import apply_op, dump_json, load_json, sha256_of  # noqa: E402

MODES = ("estate", "catalogue")
SCHEMAS = ("schemas/inherit-v3-bundled.json", "schemas/catalogue-v3-bundled.json")
COMMENT = (
    "Generated by scripts/build-conformance-kit.py -- do not edit. Each test names "
    "a fixture, its expected result and the sha256 of both; schemas carries the "
    "sha256 of each bundled schema. INVALID fixtures are generated from "
    "mutations.json: one VALID base, one JSON Patch operation, one targeted rule."
)


def cannot(message):
    print(f"CANNOT ANSWER: {message}", file=sys.stderr)
    sys.exit(2)


def build(kit):
    """Return ({relative path: text}, [problems]) for every generated file."""
    out, problems = {}, []
    try:
        version = load_json(kit / "package.json")["version"]
        cases = load_json(kit / "mutations.json")["cases"]
    except (OSError, ValueError, KeyError) as err:
        cannot(f"cannot read the kit's package.json or mutations.json -- {err}")

    ids = [c["id"] for c in cases]
    for dup in sorted({i for i in ids if ids.count(i) > 1}):
        problems.append(f"mutations.json: id {dup} is used more than once")

    tests = []
    for mode in MODES:
        for path in sorted((kit / mode / "valid").glob("*.json")):
            rel = str(path.relative_to(kit))
            exp_rel = f"expected/{path.stem}.expected.json"
            if not (kit / exp_rel).exists():
                problems.append(f"{rel} has no {exp_rel}")
                continue
            expected = load_json(kit / exp_rel)
            if expected.get("valid") is not True or expected.get("schemaMode") != mode:
                problems.append(f"{exp_rel} must say valid: true, schemaMode: {mode}")
            entry = {"file": rel, "sha256": sha256_of(path), "expected": exp_rel,
                     "expectedSha256": sha256_of(kit / exp_rel), "valid": True, "schemaMode": mode}
            if expected.get("note"):
                entry["note"] = expected["note"]
            tests.append(entry)

    for case in cases:
        mode = case["schemaMode"]
        if mode not in MODES:
            problems.append(f"mutations.json: {case['id']} has schemaMode {mode!r}")
            continue
        try:
            base = load_json(kit / case["base"])
            mutant = apply_op(base, case["op"])
        except (OSError, KeyError, IndexError, ValueError) as err:
            problems.append(f"mutations.json: {case['id']} cannot be built -- {err!r}")
            continue
        rel = f"{mode}/invalid/{case['id']}.json"
        exp_rel = f"expected/{case['id']}.expected.json"
        expected = {"valid": False, "schemaMode": mode, "minErrors": 1,
                    "description": case["description"], "rule": case["rule"],
                    "base": case["base"], "op": case["op"]}
        out[rel] = dump_json(mutant)
        out[exp_rel] = dump_json(expected)
        tests.append({"file": rel, "sha256": _sha(out[rel]), "expected": exp_rel,
                      "expectedSha256": _sha(out[exp_rel]), "valid": False, "schemaMode": mode,
                      "rule": case["rule"]})

    schemas = []
    for rel in SCHEMAS:
        if not (kit / rel).exists():
            cannot(f"packages/conformance/{rel} does not exist")
        schemas.append({"file": rel, "sha256": sha256_of(kit / rel)})

    out["manifest.json"] = dump_json({
        "$comment": COMMENT,
        "name": "INHERIT Conformance Test Kit",
        "version": version,
        "schemaVersion": "v3",
        "schemas": schemas,
        "tests": tests,
    })
    return out, problems


def _sha(text):
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", default=str(Path(__file__).resolve().parent.parent))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    kit = Path(args.root) / "packages" / "conformance"
    if not kit.is_dir():
        cannot(f"{kit} does not exist")

    out, problems = build(kit)
    generated_invalid = {rel for rel in out if "/invalid/" in rel}
    strays = sorted(str(p.relative_to(kit)) for m in MODES for p in (kit / m / "invalid").glob("*.json")
                    if str(p.relative_to(kit)) not in generated_invalid)

    if args.check:
        for rel, text in sorted(out.items()):
            path = kit / rel
            if not path.exists():
                problems.append(f"{rel} is missing -- run scripts/build-conformance-kit.py")
            elif path.read_text(encoding="utf-8") != text:
                problems.append(f"{rel} differs from a rebuild -- run scripts/build-conformance-kit.py")
        for rel in strays:
            problems.append(f"{rel} is not generated from mutations.json")
    else:
        for rel in strays:
            (kit / rel).unlink()
            stale_expected = kit / "expected" / (Path(rel).stem + ".expected.json")
            if stale_expected.exists():
                stale_expected.unlink()
        for rel, text in out.items():
            (kit / rel).parent.mkdir(parents=True, exist_ok=True)
            (kit / rel).write_text(text, encoding="utf-8")

    if problems:
        for p in problems:
            print(p, file=sys.stderr)
        sys.exit(1)
    print(f"conformance kit: {'current' if args.check else 'built'} -- "
          f"{len(generated_invalid)} INVALID mutations")


if __name__ == "__main__":
    main()
