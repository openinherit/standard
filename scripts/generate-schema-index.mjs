/**
 * Generate v3/index.json, the list of every schema under v3/ — or, with
 * --check, refuse when the committed index no longer matches the tree.
 *
 * A schema is any .json file under v3/ with a top-level "$schema". Each entry
 * records its path, $id and title, sorted by path. The index has no "$schema"
 * of its own, so it never lists itself.
 *
 * Two kinds of .json under v3/ are not schemas and are deliberately left out:
 * extension manifests (extensions/<name>/extension.json) and the JSON-LD
 * context (context/). Any other .json without "$schema" is refused, so a
 * schema that loses its "$schema" cannot drop out of the index unnoticed.
 *
 * Exit 0 written / current · 1 refused (stale index, or a .json that is not a
 * schema, manifest or context; each finding printed) · 2 cannot answer (no
 * v3/, no index to check, an unparseable .json, a bad argument). Never read 2
 * as clear.
 *
 * Usage: node scripts/generate-schema-index.mjs [--check] [--root <repo>]
 */
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'fs';
import { join, relative, resolve, dirname, basename, sep } from 'path';
import { fileURLToPath } from 'url';

const VERSION_DIR = 'v3';
const INDEX = 'index.json';

let root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
let check = false;
const args = process.argv.slice(2);
for (let i = 0; i < args.length; i++) {
  if (args[i] === '--check') check = true;
  else if (args[i] === '--root' && args[i + 1]) root = resolve(args[++i]);
  else cannotAnswer(`unknown argument ${args[i]}`);
}

function cannotAnswer(msg) {
  console.error(`CANNOT ANSWER — ${msg}`);
  process.exit(2);
}

const dir = join(root, VERSION_DIR);
if (!existsSync(dir) || !statSync(dir).isDirectory()) cannotAnswer(`no ${VERSION_DIR}/ directory at ${root}`);

const walk = (d) => readdirSync(d, { withFileTypes: true }).flatMap((e) =>
  e.isDirectory() ? walk(join(d, e.name)) : [join(d, e.name)]);
const posix = (p) => p.split(sep).join('/');

const schemas = [];
const refused = [];
for (const file of walk(dir).filter((f) => f.endsWith('.json')).sort()) {
  const path = posix(relative(root, file));
  if (path === `${VERSION_DIR}/${INDEX}`) continue;
  let doc;
  try {
    doc = JSON.parse(readFileSync(file, 'utf8'));
  } catch (e) {
    cannotAnswer(`${path} does not parse: ${e.message}`);
  }
  if (doc && typeof doc === 'object' && '$schema' in doc) {
    schemas.push({ path, $id: doc.$id ?? null, title: doc.title ?? null });
  } else if (basename(path) === 'extension.json' && path.startsWith(`${VERSION_DIR}/extensions/`)) {
    // an extension manifest, described by extensions-registry.json
  } else if (path.startsWith(`${VERSION_DIR}/context/`)) {
    // the JSON-LD context
  } else {
    refused.push(`${path} has no "$schema" and is not an extension manifest or the JSON-LD context`);
  }
}
schemas.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));

const index = {
  $comment: 'GENERATED by scripts/generate-schema-index.mjs — do not hand-edit. Regenerate with `node scripts/generate-schema-index.mjs` and copy to packages/schema/v3/. Lists every schema under v3/. The v3 in each path and $id is the identifier namespace, not the release: see docs/policies/versioning.md.',
  directory: VERSION_DIR,
  count: schemas.length,
  schemas,
};
const text = `${JSON.stringify(index, null, 2)}\n`;
const indexPath = join(dir, INDEX);

if (refused.length) {
  for (const f of refused) console.error(`REFUSED — ${f}`);
  process.exit(1);
}

if (!check) {
  writeFileSync(indexPath, text);
  console.log(`Wrote ${VERSION_DIR}/${INDEX} — ${schemas.length} schemas`);
  process.exit(0);
}

if (!existsSync(indexPath)) cannotAnswer(`no ${VERSION_DIR}/${INDEX} to check — run without --check to generate it`);
const committed = readFileSync(indexPath, 'utf8');
if (committed === text) {
  console.log(`OK — ${VERSION_DIR}/${INDEX} lists all ${schemas.length} schemas and matches the tree`);
  process.exit(0);
}

// Stale. Say how, as precisely as the committed file allows.
const findings = [];
let listed = [];
try {
  listed = JSON.parse(committed).schemas ?? [];
} catch {
  findings.push(`${VERSION_DIR}/${INDEX} does not parse`);
}
const was = new Map(listed.map((e) => [e.path, e]));
const now = new Map(schemas.map((e) => [e.path, e]));
for (const p of now.keys()) if (!was.has(p)) findings.push(`${p} is a schema but is not in the index`);
for (const p of was.keys()) if (!now.has(p)) findings.push(`${p} is in the index but is not a schema in the tree`);
for (const [p, e] of now) {
  const w = was.get(p);
  if (w && (w.$id !== e.$id || w.title !== e.title)) findings.push(`${p}: the index records a different $id or title`);
}
if (!findings.length) findings.push(`${VERSION_DIR}/${INDEX} differs from what the generator writes (hand-edited or reformatted)`);
for (const f of findings) console.error(`REFUSED — ${f}`);
console.error(`Run: node scripts/generate-schema-index.mjs && cp ${VERSION_DIR}/${INDEX} packages/schema/${VERSION_DIR}/${INDEX}`);
process.exit(1);
