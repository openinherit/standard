#!/usr/bin/env python3
"""Emit the conditional layer for both generated runtime validators.

The Zod and pydantic generators drop three things that v3/ relies on:

  1. an `if` / `then` / `else` keyed on one member's const value: a
     discriminator, such as the root's `conformanceProfile`;
  2. validation keywords next to a `$ref`, such as catalogue.json's
     `conformance: {$ref, properties: {profile: {const: "catalogue"}}}`;
  3. `unevaluatedProperties: false`, wherever (1) decides which members are
     evaluated.

Without this layer, a regenerated root validator accepts a document with no
`estate`, `people` or `schemaVersion`. This script reads the v3/ sources and
compiles exactly those constructs into rule data. It emits that data, with a
small evaluator, into each validator:

  zod       packages/sdk/src/zod/conditionals.ts holds the rules and the
            evaluator. zod.gen.ts is rewritten so that each affected schema,
            straight after its generated definition, becomes an intersection
            with a superRefine under its own name. Every later reference
            (a parent's items, a nested member, index.ts) then gets the
            layered schema, at any depth, the way pydantic's class
            validators apply wherever a class is used.
  pydantic  packages/sdk-python/openinherit/models.py. Each affected class
            gains a model_validator(mode="after"). It checks the instance's
            JSON dump: by alias, unset members excluded, extras included. That
            is the members the document supplied. Not "before" or "wrap":
            under validate_json(strict=True), the dict those hand back is
            re-validated as Python input, which refuses ISO date strings.
            pydantic also discards, before any validator sees it, an input key
            equal to the Python name of an aliased field (field_schema for
            $schema). For a closed class, its __pydantic_validator__ is
            wrapped so those keys are refused on the raw input first.

Both evaluators also refuse null for any top-level member whose schema
cannot be null. The generated pydantic fields for members a branch requires
are Optional, and "present" must not be satisfied by null.

Inside a branch or overlay, the layer evaluates only: required, const, enum,
minItems, maxItems, minimum, maximum, exclusiveMinimum, exclusiveMaximum,
properties, allOf, not, contains, if/then/else, and $ref to a whole v3 document
schema. A $ref is delegated to that schema's own
(layered) validator. Annotations are ignored. Any other keyword in those
positions is a hard failure, so a construct the layer cannot evaluate can
never be dropped silently.

Usage: write-conditional-layer.py zod <openapi-bundled.yaml> <zod output dir>
       write-conditional-layer.py pydantic <openapi-bundled.yaml> <models.py>
"""
import json
import re
from pprint import pformat
import sys
from pathlib import Path
from urllib.parse import urljoin

import yaml

HEADER = "This file is generated by scripts/generate-runtime-validators.sh — do not edit."
ROOT = Path(__file__).resolve().parents[2]

ANNOTATIONS = {
    "$comment", "description", "title", "examples", "default", "deprecated",
    "readOnly", "writeOnly", "$id", "$schema", "x-inherit-pii",
}
SUPPORTED = {
    "required", "const", "enum", "minItems", "maxItems", "properties",
    "allOf", "not", "contains", "if", "then", "else", "$ref",
    "minimum", "maximum", "exclusiveMinimum", "exclusiveMaximum",
}
APPLICATORS = ("allOf", "anyOf", "oneOf", "if", "then", "else", "dependentSchemas", "$ref")


def fail(msg: str) -> None:
    print(f"write-conditional-layer: {msg}", file=sys.stderr)
    sys.exit(1)


def pascal(key: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in re.split(r"[^A-Za-z0-9]+", key) if p)


def components(bundle: Path) -> dict[str, str]:
    """$id -> generated name stem, for every bundle component that has an $id."""
    schemas = yaml.safe_load(bundle.read_text())["components"]["schemas"]
    return {b["$id"]: pascal(k) for k, b in schemas.items() if isinstance(b, dict) and b.get("$id")}


def sources() -> dict[str, dict]:
    out = {}
    for f in sorted((ROOT / "v3").rglob("*.json")):
        try:
            doc = json.loads(f.read_text())
        except json.JSONDecodeError:
            continue
        if isinstance(doc, dict) and isinstance(doc.get("$id"), str):
            out[doc["$id"]] = doc
    return out


def is_discriminator(cond: dict) -> bool:
    """if: {required: [p], properties: {p: {const: v}}}, the only `if` shape compiled."""
    s = cond.get("if")
    if not isinstance(s, dict) or set(s) - {"required", "properties"} or "properties" not in s:
        return False
    props = s["properties"]
    if len(props) != 1:
        return False
    (p, sub), = props.items()
    return isinstance(sub, dict) and set(sub) == {"const"} and s.get("required", [p]) == [p]


class Compiler:
    def __init__(self, ids: dict[str, str], srcs: dict[str, dict]):
        self.ids, self.srcs, self.refs = ids, srcs, set()

    def compile(self, s, base: str, where: str):
        if s is True or s is None:
            return {}
        if not isinstance(s, dict):
            fail(f"{where}: cannot evaluate {s!r}")
        out = {}
        for k, v in s.items():
            if k in ANNOTATIONS:
                continue
            if k not in SUPPORTED:
                fail(f"{where}: keyword {k!r} is not one the layer evaluates. Extend the layer, or restructure the schema")
            if k == "$ref":
                target = urljoin(base, v)
                if "#" in target or target not in self.ids:
                    fail(f"{where}: $ref {v!r} is not a whole v3 document schema with a generated validator")
                self.refs.add(target)
                out["$ref"] = target
            elif k == "properties":
                out[k] = {p: self.compile(sub, base, f"{where}/properties/{p}") for p, sub in v.items()}
            elif k == "allOf":
                out[k] = [self.compile(sub, base, f"{where}/allOf/{i}") for i, sub in enumerate(v)]
            elif k in ("not", "contains", "if", "then", "else"):
                out[k] = self.compile(v, base, f"{where}/{k}")
            else:
                out[k] = v
        return out

    def rule(self, sid: str):
        doc = self.srcs.get(sid)
        if doc is None:
            return None
        members = [m for m in doc.get("allOf", []) if isinstance(m, dict) and "if" in m]
        if "if" in doc:
            members.append({k: doc[k] for k in ("if", "then", "else") if k in doc})
        conds = [
            self.compile({k: m[k] for k in ("if", "then", "else") if k in m}, sid, f"{sid} allOf conditional")
            for m in members if is_discriminator(m)
        ]
        # Everything the layer does not compile may still evaluate members.
        # For unevaluatedProperties, count every member name it could
        # evaluate. Over-counting can only accept more, never refuse a valid
        # document.
        others = [m for m in doc.get("allOf", []) if not (isinstance(m, dict) and "if" in m and is_discriminator(m))]
        others += [{k: doc[k]} for k in APPLICATORS if k in doc and k != "allOf" and not (k in ("if", "then", "else") and is_discriminator(doc))]
        overlays = {}
        for p, sub in doc.get("properties", {}).items():
            if isinstance(sub, dict) and "$ref" in sub:
                rest = {k: v for k, v in sub.items() if k != "$ref" and k not in ANNOTATIONS}
                if rest:
                    overlays[p] = self.compile(rest, sid, f"{sid} properties/{p} (next to $ref)")
        if not conds and not overlays:
            return None
        rule = {"conditionals": conds, "overlays": overlays, "closed": None,
                "nonnull": sorted(p for p, sub in doc.get("properties", {}).items() if self.nonnull(sub, sid, set()))}
        if doc.get("unevaluatedProperties") is False or doc.get("additionalProperties") is False:
            names, patterns = set(doc.get("properties", {})), set(doc.get("patternProperties", {}))
            if all(self.reach(m, sid, names, patterns, set()) for m in others):
                rule["closed"] = {"props": sorted(names), "patterns": sorted(patterns)}
            else:
                print(f"write-conditional-layer: {sid}: unevaluatedProperties left to the generated validator "
                      "(a member it cannot resolve could evaluate any name)", file=sys.stderr)
        return rule

    def nonnull(self, s, base, seen) -> bool:
        """True only when s certainly refuses null. Unsure means False, which never refuses."""
        if not isinstance(s, dict):
            return s is False
        t = s.get("type")
        if t is not None:
            return "null" not in (t if isinstance(t, list) else [t])
        if "const" in s:
            return s["const"] is not None
        if "enum" in s:
            return None not in s["enum"]
        if any(self.nonnull(x, base, seen) for x in s.get("allOf", [])):
            return True
        if "$ref" in s:
            target = urljoin(base, s["$ref"])
            doc_id, _, frag = target.partition("#")
            node = self.srcs.get(doc_id)
            for part in [p for p in frag.split("/") if p]:
                node = node.get(part.replace("~1", "/").replace("~0", "~")) if isinstance(node, dict) else None
            if node is None or target in seen:
                return False
            return self.nonnull(node, doc_id, seen | {target})
        return False

    def reach(self, s, base, names, patterns, seen) -> bool:
        """Every member name s could evaluate, added to names/patterns. False if unknowable."""
        if not isinstance(s, dict):
            return isinstance(s, bool)
        names.update(s.get("properties", {}))
        patterns.update(s.get("patternProperties", {}))
        if "additionalProperties" in s or "unevaluatedProperties" in s and s["unevaluatedProperties"] is not False:
            return False
        if "$ref" in s:
            target = urljoin(base, s["$ref"])
            if "#" in target or target not in self.srcs:
                return False
            if target not in seen:
                seen.add(target)
                t = self.srcs[target]
                if not self.reach({k: v for k, v in t.items() if k in ("properties", "patternProperties", *APPLICATORS)}, target, names, patterns, seen):
                    return False
        for k in ("allOf", "anyOf", "oneOf"):
            if not all(self.reach(x, base, names, patterns, seen) for x in s.get(k, [])):
                return False
        for k in ("if", "then", "else"):
            if k in s and not self.reach(s[k], base, names, patterns, seen):
                return False
        return all(self.reach(x, base, names, patterns, seen) for x in s.get("dependentSchemas", {}).values())


def keys(doc: dict) -> dict:
    return {"props": sorted(doc.get("properties", {})), "patterns": sorted(doc.get("patternProperties", {}))}


def build(bundle: Path):
    ids, srcs = components(bundle), sources()
    c = Compiler(ids, srcs)
    rules = {sid: r for sid in sorted(ids) if (r := c.rule(sid))}
    refkeys = {sid: keys(srcs[sid]) for sid in sorted(c.refs)}
    return ids, rules, refkeys


