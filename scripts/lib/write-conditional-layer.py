ZOD_EVAL = r"""
type Rule = { conditionals: any[]; overlays: Record<string, any>; closed: { props: string[]; patterns: string[] } | null; nonnull: string[] };
type Issue = { path: (string | number)[]; message: string };

const isObj = (v: unknown): v is Record<string, unknown> => v !== null && typeof v === 'object' && !Array.isArray(v);
const canon = (v: unknown): unknown => Array.isArray(v) ? v.map(canon)
  : isObj(v) ? Object.fromEntries(Object.keys(v).sort().map((k) => [k, canon(v[k])])) : v;
const same = (a: unknown, b: unknown) => JSON.stringify(canon(a)) === JSON.stringify(canon(b));

function evaluate(s: any, v: unknown, path: (string | number)[], out: Issue[]): void {
  if (s.$ref !== undefined) {
    const r = byId(s.$ref).safeParse(v);
    if (!r.success) for (const i of r.error.issues) out.push({ path: [...path, ...(i.path as (string | number)[])], message: i.message });
  }
  if (s.const !== undefined && !same(v, s.const)) out.push({ path, message: `must be ${JSON.stringify(s.const)}` });
  if (s.enum !== undefined && !s.enum.some((e: unknown) => same(v, e))) out.push({ path, message: `must be one of ${JSON.stringify(s.enum)}` });
  if (typeof v === 'number') {
    if (s.minimum !== undefined && v < s.minimum) out.push({ path, message: `must be >= ${s.minimum}` });
    if (s.maximum !== undefined && v > s.maximum) out.push({ path, message: `must be <= ${s.maximum}` });
    if (s.exclusiveMinimum !== undefined && v <= s.exclusiveMinimum) out.push({ path, message: `must be > ${s.exclusiveMinimum}` });
    if (s.exclusiveMaximum !== undefined && v >= s.exclusiveMaximum) out.push({ path, message: `must be < ${s.exclusiveMaximum}` });
  }
  if (Array.isArray(v)) {
    if (s.maxItems !== undefined && v.length > s.maxItems) out.push({ path, message: `must have at most ${s.maxItems} items` });
    if (s.minItems !== undefined && v.length < s.minItems) out.push({ path, message: `must have at least ${s.minItems} items` });
    if (s.contains !== undefined && !v.some((x) => passes(s.contains, x))) out.push({ path, message: 'must contain a matching item' });
  }
  if (isObj(v)) {
    for (const k of s.required ?? []) if (!(k in v)) out.push({ path: [...path, k], message: `required: ${k}` });
    for (const [k, sub] of Object.entries(s.properties ?? {})) if (k in v) evaluate(sub, v[k], [...path, k], out);
  }
  for (const sub of s.allOf ?? []) evaluate(sub, v, path, out);
  if (s.not !== undefined && passes(s.not, v)) out.push({ path, message: 'must not match the excluded shape' });
  if (s.if !== undefined) {
    const branch = passes(s.if, v) ? s.then : s.else;
    if (branch !== undefined) evaluate(branch, v, path, out);
  }
}

function passes(s: any, v: unknown): boolean {
  const out: Issue[] = [];
  evaluate(s, v, [], out);
  return out.length === 0;
}

/** Member names a branch evaluates, for unevaluatedProperties. */
function evaluated(s: any, names: Set<string>, patterns: string[]): void {
  for (const k of Object.keys(s.properties ?? {})) names.add(k);
  if (s.$ref !== undefined) {
    const k = REFKEYS[s.$ref];
    for (const p of k.props) names.add(p);
    patterns.push(...k.patterns);
  }
  for (const sub of s.allOf ?? []) evaluated(sub, names, patterns);
}

function check(id: string, v: unknown): Issue[] {
  const rule: Rule = RULES[id];
  const out: Issue[] = [];
  if (!isObj(v)) return out;
  const names = new Set<string>(rule.closed?.props ?? []);
  const patterns = [...(rule.closed?.patterns ?? [])];
  for (const c of rule.conditionals) {
    const ok = passes(c.if, v);
    const branch = ok ? c.then : c.else;
    if (ok) evaluated(c.if, names, patterns);
    if (branch !== undefined) {
      evaluate(branch, v, [], out);
      evaluated(branch, names, patterns);
    }
  }
  for (const k of rule.nonnull) if (k in v && v[k] === null) out.push({ path: [k], message: `${k} must not be null` });
  for (const [k, sub] of Object.entries(rule.overlays)) if (k in v) evaluate(sub, v[k], [k], out);
  if (rule.closed) {
    const res = patterns.map((p) => new RegExp(p, 'u'));
    for (const k of Object.keys(v)) {
      if (!names.has(k) && !res.some((r) => r.test(k))) out.push({ path: [k], message: `${k} is not allowed here (unevaluatedProperties)` });
    }
  }
  return out;
}

const REGISTRY: Record<string, z.ZodType> = {};

function byId(id: string): z.ZodType {
  const s = REGISTRY[id];
  if (!s) throw new Error(`conditional layer: no validator registered for ${id}`);
  return s;
}

/** Called by zod.gen.ts for a schema a branch delegates to by $ref. */
export function register<T extends z.ZodType>(id: string, schema: T): T {
  REGISTRY[id] = schema;
  return schema;
}

/** Called by zod.gen.ts straight after each layered schema's generated definition. */
export function layer<T extends z.ZodType>(id: string, base: T) {
  if (!RULES[id]) throw new Error(`conditional layer: no rule for ${id}`);
  return register(id, z.intersection(base, z.unknown().superRefine((v, ctx) => {
    for (const i of check(id, v)) ctx.addIssue({ code: 'custom', path: i.path, message: i.message });
  })));
}
"""


def zod(bundle: Path, out_dir: Path) -> None:
    ids, rules, refkeys = build(bundle)
    gen_path = out_dir / "zod.gen.ts"
    lines = gen_path.read_text().split("\n")

    def definition(name: str) -> tuple[int, int]:
        heads = [i for i, l in enumerate(lines) if l.startswith(f"export const {name} = ")]
        if len(heads) != 1:
            fail(f"zod.gen.ts: expected one definition of {name}, found {len(heads)}")
        i = heads[0]
        for j in range(i, len(lines)):
            if (j == i or not lines[j].startswith((" ", "\t"))) and lines[j].rstrip().endswith(";"):
                return i, j
        fail(f"zod.gen.ts: cannot find the end of {name}")

    edits = []
    for sid in sorted({*rules, *refkeys}):
        name = "z" + ids[sid]
        i, j = definition(name)
        if sid in rules:
            edits.append((i, j, name, f"export const {name} = layer('{sid}', {name}$generated);"))
        else:
            edits.append((i, j, None, f"register('{sid}', {name});"))
    for i, j, name, after in sorted(edits, reverse=True):
        lines.insert(j + 1, after)
        if name:
            lines[i] = lines[i].replace(f"export const {name} = ", f"const {name}$generated = ", 1)
    imp = next((k for k, l in enumerate(lines) if l.startswith("import ") and "'zod'" in l), None)
    if imp is None:
        fail("zod.gen.ts has no zod import to follow")
    lines.insert(imp + 1, "import { layer, register } from './conditionals';")
    gen_path.write_text("\n".join(lines))

    out = [
        f"// {HEADER}",
        "//",
        "// The conditional layer's rules and evaluator. zod.gen.ts applies it; see",
        "// scripts/lib/write-conditional-layer.py for what it evaluates and why the",
        "// generated schemas cannot.",
        "",
        "import * as z from 'zod';",
        "",
        f"const RULES: Record<string, Rule> = {json.dumps(rules, indent=2, ensure_ascii=False)};",
        "",
        f"const REFKEYS: Record<string, {{ props: string[]; patterns: string[] }}> = {json.dumps(refkeys, indent=2, ensure_ascii=False)};",
        ZOD_EVAL,
    ]
    (out_dir / "conditionals.ts").write_text("\n".join(out))
    print(f"write-conditional-layer: zod — {len(rules)} schemas layered in place "
          f"({', '.join('z' + ids[s] for s in sorted(rules, key=lambda s: ids[s]))})")


