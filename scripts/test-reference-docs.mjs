/**
 * Tests for scripts/generate-reference-docs.mjs.
 *
 * Hermetic: each test builds a synthetic v3/ tree in a temp directory, so a
 * green here says the generator renders and checks correctly — not that the
 * committed docs/reference/ is current. That second question is answered by
 * `node scripts/generate-reference-docs.mjs --check`.
 *
 * Run: node --test scripts/test-reference-docs.mjs
 */

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

import { generateAll } from './generate-reference-docs.mjs';

const SCRIPT = join(dirname(fileURLToPath(import.meta.url)), 'generate-reference-docs.mjs');

function tree(files) {
  const root = mkdtempSync(join(tmpdir(), 'refdocs-'));
  for (const [rel, body] of Object.entries(files)) {
    mkdirSync(dirname(join(root, rel)), { recursive: true });
    writeFileSync(join(root, rel), typeof body === 'string' ? body : JSON.stringify(body, null, 2));
  }
  return root;
}

const money = {
  $id: 'https://openinherit.org/v3/common/money.json',
  title: 'Money',
  description: 'An amount in minor units.',
  type: 'object',
  required: ['amount'],
  properties: {
    amount: { type: 'integer', description: 'Minor units.' },
    currency: { type: 'string', enum: ['GBP', 'USD'], description: 'ISO 4217.' },
  },
};

const person = {
  $id: 'https://openinherit.org/v3/person.json',
  title: 'Person',
  description: 'A person.',
  type: 'object',
  required: ['id'],
  properties: {
    id: { type: 'string', description: 'Identifier | with a pipe\nand a newline' },
    wealth: { $ref: 'common/money.json' },
    absolute: { $ref: 'https://openinherit.org/v3/common/money.json' },
    nowhere: { $ref: 'does-not-exist.json', description: 'Dangling on purpose.' },
    aliases: { type: 'array', items: { $ref: '#/$defs/alias' }, description: 'Other names <b>.' },
  },
  $defs: {
    alias: {
      type: 'object',
      properties: { value: { type: 'string', description: 'The alias.' } },
    },
  },
};

const base = () => tree({
  'v3/person.json': person,
  'v3/common/money.json': money,
  'v3/dialect.json': { $id: 'https://openinherit.org/v3/dialect.json', title: 'Dialect' },
});

test('renders one page per schema plus an index, and skips the dialect', () => {
  const root = base();
  try {
    const pages = generateAll(root);
    assert.deepEqual([...pages.keys()].sort(), [
      'docs/reference/README.md',
      'docs/reference/common/money.md',
      'docs/reference/person.md',
    ]);
  } finally { rmSync(root, { recursive: true }); }
});

test('marks the page as generated and links its source schema', () => {
  const root = base();
  try {
    const page = generateAll(root).get('docs/reference/person.md');
    assert.match(page, /^<!-- GENERATED by scripts\/generate-reference-docs\.mjs/);
    assert.match(page, /\[`v3\/person\.json`\]\(\.\.\/\.\.\/v3\/person\.json\)/);
  } finally { rmSync(root, { recursive: true }); }
});

test('escapes pipes, newlines and angle brackets inside table cells', () => {
  const root = base();
  try {
    const page = generateAll(root).get('docs/reference/person.md');
    const row = page.split('\n').find((l) => l.startsWith('| `id`'));
    assert.ok(row, 'id row present');
    assert.match(row, /Identifier \\\| with a pipe and a newline/);
    assert.match(page, /Other names &lt;b&gt;\./);
  } finally { rmSync(root, { recursive: true }); }
});

test('marks required properties', () => {
  const root = base();
  try {
    const page = generateAll(root).get('docs/reference/person.md');
    assert.match(page, /\| `id` \| `string` \| yes \|/);
    assert.match(page, /\| `wealth` \| \[Money\]\(common\/money\.md\) \| \|/);
  } finally { rmSync(root, { recursive: true }); }
});

test('relative and absolute $refs both link to the generated page; a dangling one stays code', () => {
  const root = base();
  try {
    const page = generateAll(root).get('docs/reference/person.md');
    assert.match(page, /\| `absolute` \| \[Money\]\(common\/money\.md\) \|/);
    assert.match(page, /\| `nowhere` \| `\$ref: does-not-exist\.json` \|/);
  } finally { rmSync(root, { recursive: true }); }
});

test('local $defs refs link to an explicit anchor that the page defines', () => {
  const root = base();
  try {
    const page = generateAll(root).get('docs/reference/person.md');
    assert.match(page, /\| `aliases` \| array of \[alias\]\(#def-alias\) \|/);
    assert.match(page, /<a id="def-alias"><\/a>/);
  } finally { rmSync(root, { recursive: true }); }
});

test('renders enums inline', () => {
  const root = base();
  try {
    const page = generateAll(root).get('docs/reference/common/money.md');
    assert.match(page, /\| `currency` \| `string` — one of `GBP`, `USD` \|/);
  } finally { rmSync(root, { recursive: true }); }
});

test('output is independent of key order in the source', () => {
  const a = base();
  const shuffled = { ...person, properties: Object.fromEntries(Object.entries(person.properties).reverse()) };
  const b = tree({ 'v3/person.json': shuffled, 'v3/common/money.json': money });
  try {
    // Properties render in source order (that order is meaningful to readers),
    // but pages, the index and $defs are sorted, so filesystem order never leaks.
    const ia = generateAll(a).get('docs/reference/README.md');
    const ib = generateAll(b).get('docs/reference/README.md');
    assert.equal(ia, ib);
  } finally { rmSync(a, { recursive: true }); rmSync(b, { recursive: true }); }
});

function cli(root, ...args) {
  return spawnSync(process.execPath, [SCRIPT, '--root', root, ...args], { encoding: 'utf-8' });
}

test('--check is green straight after a write', () => {
  const root = base();
  try {
    assert.equal(cli(root).status, 0);
    const r = cli(root, '--check');
    assert.equal(r.status, 0, r.stdout + r.stderr);
  } finally { rmSync(root, { recursive: true }); }
});

test('--check goes RED on a hand-edited page', () => {
  const root = base();
  try {
    cli(root);
    const p = join(root, 'docs/reference/person.md');
    writeFileSync(p, readFileSync(p, 'utf-8') + '\nhand edit\n');
    const r = cli(root, '--check');
    assert.equal(r.status, 1);
    assert.match(r.stdout, /STALE\s+docs\/reference\/person\.md/);
  } finally { rmSync(root, { recursive: true }); }
});

test('--check goes RED when a schema changes without regeneration', () => {
  const root = base();
  try {
    cli(root);
    writeFileSync(join(root, 'v3/common/money.json'),
      JSON.stringify({ ...money, description: 'Changed.' }));
    const r = cli(root, '--check');
    assert.equal(r.status, 1);
    assert.match(r.stdout, /STALE\s+docs\/reference\/common\/money\.md/);
  } finally { rmSync(root, { recursive: true }); }
});

test('--check goes RED on a missing page and on an orphaned one', () => {
  const root = base();
  try {
    cli(root);
    rmSync(join(root, 'docs/reference/common/money.md'));
    writeFileSync(join(root, 'docs/reference/ghost.md'), 'left behind\n');
    const r = cli(root, '--check');
    assert.equal(r.status, 1);
    assert.match(r.stdout, /MISSING\s+docs\/reference\/common\/money\.md/);
    assert.match(r.stdout, /ORPHAN\s+docs\/reference\/ghost\.md/);
  } finally { rmSync(root, { recursive: true }); }
});

test('exits 2, never 0, when there is no v3/ tree to read', () => {
  const root = mkdtempSync(join(tmpdir(), 'refdocs-empty-'));
  try {
    assert.equal(cli(root, '--check').status, 2);
  } finally { rmSync(root, { recursive: true }); }
});

test('index summaries do not cut at an abbreviation', () => {
  const root = tree({
    'v3/asset-collection.json': {
      title: 'Asset Collection',
      description: 'A named group of related assets — e.g. a stamp collection. Second sentence.',
      type: 'object',
    },
  });
  try {
    const index = generateAll(root).get('docs/reference/README.md');
    assert.match(index, /\| A named group of related assets — e\.g\. a stamp collection\. \|/);
  } finally { rmSync(root, { recursive: true }); }
});

test('a pure $defs ref with no description borrows the definition\'s description', () => {
  const root = tree({
    'v3/ext.json': {
      title: 'Ext',
      type: 'object',
      properties: { dower: { $ref: '#/$defs/Dower' } },
      $defs: { Dower: { type: 'object', description: 'Dower rights.' } },
    },
  });
  try {
    const page = generateAll(root).get('docs/reference/ext.md');
    assert.match(page, /\| `dower` \| \[Dower\]\(#def-Dower\) \| \| Dower rights\. \|/);
  } finally { rmSync(root, { recursive: true }); }
});

test('a cross-file ref into a non-$defs fragment stays code rather than linking the whole page', () => {
  const root = tree({
    'v3/schema.json': { title: 'Document', type: 'object', properties: { people: { type: 'array' } } },
    'v3/catalogue.json': {
      title: 'Catalogue',
      type: 'object',
      properties: { people: { $ref: 'schema.json#/properties/people' } },
    },
  });
  try {
    const page = generateAll(root).get('docs/reference/catalogue.md');
    assert.match(page, /\| `people` \| `\$ref: schema\.json#\/properties\/people` \|/);
  } finally { rmSync(root, { recursive: true }); }
});

test('a schema in a new directory is documented and indexed, not silently skipped', () => {
  const root = tree({
    'v3/person.json': person,
    'v3/common/money.json': money,
    'v3/novel/thing.json': { title: 'Thing', description: 'New. More.', type: 'object' },
  });
  try {
    const pages = generateAll(root);
    assert.ok(pages.has('docs/reference/novel/thing.md'));
    assert.match(pages.get('docs/reference/README.md'), /## Other schemas[\s\S]*\[Thing\]\(novel\/thing\.md\) \| New\. \|/);
  } finally { rmSync(root, { recursive: true }); }
});

test('metaschemas, JSON-LD contexts and extension manifests are skipped by rule', () => {
  const root = tree({
    'v3/person.json': person,
    'v3/common/money.json': money,
    'v3/vocab/estate/meta.json': { title: 'Meta' },
    'v3/context/inherit-v3.json': { '@context': {} },
    'v3/extensions/canada/canada.json': { title: 'Canada', type: 'object' },
    'v3/extensions/canada/extension.json': { name: 'canada' },
  });
  try {
    const keys = [...generateAll(root).keys()].sort();
    assert.deepEqual(keys, [
      'docs/reference/README.md',
      'docs/reference/common/money.md',
      'docs/reference/extensions/canada/canada.md',
      'docs/reference/person.md',
    ]);
  } finally { rmSync(root, { recursive: true }); }
});

test('a pipe inside an enum value cannot split the table cell', () => {
  const root = tree({
    'v3/x.json': { title: 'X', type: 'object', properties: { op: { type: 'string', enum: ['a|b'] } } },
  });
  try {
    const page = generateAll(root).get('docs/reference/x.md');
    assert.match(page, /one of `a\\\|b`/);
  } finally { rmSync(root, { recursive: true }); }
});

test('a requirement gated on a profile discriminator is shown with its condition, not dropped', () => {
  // The shape v3/schema.json uses for conformance profiles: required in the
  // else branch of an if on a const. Reading top-level `required` alone would
  // render `estate` as optional — wrong for every document at the default.
  const root = tree({
    'v3/doc.json': {
      $id: 'https://openinherit.org/v3/doc.json',
      title: 'Doc',
      type: 'object',
      required: ['id'],
      properties: {
        id: { type: 'string' },
        profile: { enum: ['full', 'lite'] },
        estate: { type: 'object' },
        extra: { type: 'string' },
        free: { type: 'string' },
      },
      allOf: [
        {
          if: { required: ['profile'], properties: { profile: { const: 'lite' } } },
          then: { required: ['extra'] },
          else: { required: ['estate'] },
        },
      ],
    },
  });
  try {
    const page = generateAll(root).get('docs/reference/doc.md');
    assert.match(page, /\| `id` \| `string` \| yes \|/);
    assert.match(page, /\| `estate` \| `object` \| yes, unless `profile` is `lite` \|/);
    assert.match(page, /\| `extra` \| `string` \| when `profile` is `lite` \|/);
    assert.match(page, /\| `free` \| `string` \| \|/);
  } finally { rmSync(root, { recursive: true }); }
});

test('a then-branch that is only a $ref adds no row-level condition', () => {
  const root = tree({
    'v3/doc.json': {
      $id: 'https://openinherit.org/v3/doc.json',
      title: 'Doc',
      type: 'object',
      properties: { p: { const: 'x' }, a: { type: 'string' } },
      allOf: [{ if: { required: ['p'], properties: { p: { const: 'x' } } }, then: { $ref: 'other.json' } }],
    },
  });
  try {
    const page = generateAll(root).get('docs/reference/doc.md');
    assert.match(page, /\| `a` \| `string` \| \|/);
  } finally { rmSync(root, { recursive: true }); }
});

test('a property required under several discriminator values names every one of them', () => {
  const gate = (v) => ({ if: { required: ['kind'], properties: { kind: { const: v } } }, then: { required: ['ref'] } });
  const root = tree({
    'v3/doc.json': {
      $id: 'https://openinherit.org/v3/doc.json',
      title: 'Doc',
      type: 'object',
      properties: { kind: { enum: ['person', 'agent', 'organisation'] }, ref: { type: 'string' } },
      allOf: [gate('person'), gate('agent'), gate('organisation')].map((g, i) =>
        i === 1 ? { ...g, then: { required: ['other'] } } : g),
    },
  });
  try {
    const page = generateAll(root).get('docs/reference/doc.md');
    assert.match(page, /\| `ref` \| `string` \| when `kind` is `person` or `organisation` \|/);
  } finally { rmSync(root, { recursive: true }); }
});
